/// **Measured** geometry evidence for TAM-62 (figma-flutter Phase 2 ↔ Phase 6).
///
/// TAM-74 recorded that a full-screen side-by-side "looked basically right"
/// while three real defects were live, and TAM-76 that only measuring/cropping
/// caught four more. Home repeated the lesson: this file's numbers caught the
/// carousel dots being centred where the node pins them bottom-RIGHT (row B4).
/// So the geometry rows of the sweep table are produced by `tester.getRect` and
/// asserted against the `285:3464` REST dump — numbers, not a glance.
///
/// Generator for `specs/evidence/TAM-62/fidelity/render-tree/measured-geometry.md`.
///
/// Home's frame is 360 wide and 3685 tall (a scrolling feed, not a 360×800
/// device frame), so rows quote node bounding boxes and the deltas BETWEEN
/// nodes rather than absolute frame-y. `SafeArea` consumes no inset here: the
/// test view has zero padding, and the Figma status bar (285:3465) is OS chrome.
class _Row {
  _Row(this.id, this.zone, this.figma, this.actual, this.expected, this.ok);
  final String id;
  final String zone;
  final String figma;
  final String actual;
  final String expected;
  final bool ok;
}

final List<_Row> _rows = [];

void _record(
  String id,
  String zone,
  String figma, {
  required String actual,
  required String expected,
  required bool ok,
}) =>
    _rows.add(_Row(id, zone, figma, actual, expected, ok));

String _fmt(Rect r) =>
    'x=${r.left.toStringAsFixed(1)} y=${r.top.toStringAsFixed(1)} '
    '${r.width.toStringAsFixed(1)}×${r.height.toStringAsFixed(1)}';

String _size(Rect r) =>
    '${r.width.toStringAsFixed(1)}×${r.height.toStringAsFixed(1)}';

bool _near(double a, double b, [double tol = 0.5]) => (a - b).abs() <= tol;

/// A feed card's CONTENT box — the outer rect less the 1px hairline (285:3539),
/// which Flutter strokes inside. Figma's equivalent is node 285:3540.
Rect _contentBox(Rect card) => card.deflate(AppHome.cardBorder);

