    final b = StringBuffer()
      ..writeln('# TAM-62 — measured render-tree geometry vs Figma')
      ..writeln()
      ..writeln('Generated by `test/goldens/home_geometry_test.dart` '
          '(`flutter test test/goldens/home_geometry_test.dart`).')
      ..writeln()
      ..writeln('Every row is `tester.getRect` on the real widget tree, compared '
          'to the node bounding box from the Phase-2 REST dump '
          '(`scratch/home_root.json`, node `285:3464`) — the numeric half of the '
          'Phase-6 sweep. Home\'s frame is a 360×3685 scrolling feed, so rows '
          'quote node sizes and node-to-node deltas rather than absolute frame-y.')
      ..writeln()
      ..writeln('| # | Zone | Figma (Phase 2) | Expected | Measured | Verdict |')
      ..writeln('|---|---|---|---|---|---|');
    for (final r in _rows) {
      b.writeln('| ${r.id} | ${r.zone} | ${r.figma} | ${r.expected} | '
          '${r.actual} | ${r.ok ? 'matches' : 'DIFF'} |');
    }
    b
      ..writeln()
      ..writeln('**Verdict**: ${failed == 0 ? 'PASS' : 'FAIL'} — '
          '${_rows.length - failed}/${_rows.length} zones match their node.')
      ..writeln()
      ..writeln('Tolerance is 0.5px except where the row\'s `Expected` column '
          'states otherwise and says why: hugging buttons/pills (W4/A4/B5) are '
          'within ~1.5px of the node because they size to Skia\'s Inter advance '
          'widths rather than Figma\'s text engine; the card-content rows '
          '(W1/W2/W3/A1/A2) are 358 not 360 because Flutter strokes the 285:3539 '
          'hairline INSIDE the box (W1b); the help glyph (H4) is 19.05 not 20 '
          'because Figma rounded its export canvas to viewBox 20×21.');
    writeEvidence('TAM-62', 'render-tree/measured-geometry.md', b.toString());
  });

  testWidgets('measure: header (285:3482)', (tester) async {
