    expect(colOk, isTrue);
    _record('S2', 'Grid column gap', '2569:15302 → 10',
        actual: colGap.toStringAsFixed(2), expected: '10', ok: colOk);

    final rowGap = wallpaper.top - aarti.bottom;
    final rowOk = _near(rowGap, AppHome.shortcutGap);
    expect(rowOk, isTrue);
    _record('S3', 'Grid row gap', '2569:15302 → 10',
        actual: rowGap.toStringAsFixed(2), expected: '10', ok: rowOk);

    // Block padding: node 285:3508 pads 16 l/r (unchanged from TAM-62).
    final padOk = _near(aarti.left, AppHome.screenPadding) &&
        _near(mantras.right + AppHome.shortcutGap + AppHome.shortcutCardWidth,
            360 - AppHome.screenPadding, 1.5);
