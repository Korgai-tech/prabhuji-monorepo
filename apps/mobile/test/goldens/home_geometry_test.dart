    final cardOk = _near(aarti.width, AppHome.shortcutCardWidth) &&
        _near(aarti.height, AppHome.shortcutCardHeight);
    expect(cardOk, isTrue);
    _record('S1', 'Shortcut card', '2569:15302 → 103×117 r8 (TAM-132)',
        actual: _size(aarti), expected: '103×117', ok: cardOk);

    // Grid gaps: 10 across, 10 down.
    final colGap = mantras.left - aarti.right;
