  testWidgets('measure: shortcut grid (2569:15302 — TAM-132 3×2 layout)',
      (tester) async {
    await pumpHome(tester, repository: FakeHomeRepository());

    // Card: TAM-132 flipped to Figma frame 2569:15302 (6-tile system) — 3 cols
    // at ~103 dp wide. GridView computes the effective width from the
    // available 328 dp inner width minus 2×10 dp gaps ÷ 3 cols ≈ 102.67 dp,
    // which sits inside `_near`'s 0.5-dp tolerance around
    // `AppHome.shortcutCardWidth = 103`.
    final aarti = tester.getRect(find.byKey(const Key('home-shortcut-aarti_bhajans')));
    final mantras =
        tester.getRect(find.byKey(const Key('home-shortcut-mantras_stutis')));
