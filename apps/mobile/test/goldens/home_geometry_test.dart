    _record('S4', 'Grid block padding', '285:3508 → padLeft/Right 16',
        actual: 'left=${aarti.left.toStringAsFixed(1)}',
        expected: 'left=16',
        ok: padOk);

    // Grid block: 328×244 (2×117 + 10 gap = 244) — 2 rows. GridView computes
    // effective card height from the constrained crossAxis width via the aspect
    // ratio, so at 3-col × 328 dp inner width the actual card height is
    // ~116.67 dp (2× + 10 gap ≈ 243.33 dp). Widen the tolerance to 1 dp to
    // accommodate the sub-pixel rounding.
    final grid = tester.getRect(find.byKey(const Key('home-shortcut-grid')));
    final gridOk = _near(wallpaper.bottom - aarti.top, 244, 1.0);
    expect(gridOk, isTrue);
