    final logoGapOk = _near(logoGap, AppHome.logoWordmarkGap);
    expect(logoGapOk, isTrue);
    _record('H3', 'Logo → wordmark gap', '285:3484 itemSpacing = 8',
        actual: logoGap.toStringAsFixed(2), expected: '8', ok: logoGapOk);

